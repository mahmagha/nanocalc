#!/usr/bin/env node
/*
 * Generate docs/REVIEW.md: a sign-off checklist for a domain expert covering every
 * calculator's formulas, default parameters, presets and references, plus the global
 * constants and material data. Usage: node tools/review-sheet.js
 *
 * Formulas are collected by running each calculator on its example and on every option
 * of every select input (modes, shapes, structures, materials …), so each branch that
 * produces a different equation is listed once.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const listed = [...html.matchAll(/<script src="([^"]+)"/g)].map((m) => m[1]).filter((s) => s.startsWith('js/') && !s.endsWith('app.js'));
const onDisk = []
  .concat(fs.readdirSync(path.join(root, 'js')).filter((f) => f.endsWith('.js') && f !== 'app.js').map((f) => 'js/' + f))
  .concat(fs.readdirSync(path.join(root, 'js', 'calculators')).filter((f) => f.endsWith('.js')).map((f) => 'js/calculators/' + f));
const unregistered = onDisk.filter((s) => !listed.includes(s));
const scripts = listed.concat(unregistered.filter((s) => !s.includes('/calculators/')), unregistered.filter((s) => s.includes('/calculators/')));

const ctx = { console, Math, JSON };
ctx.window = ctx;
ctx.globalThis = ctx;
vm.createContext(ctx);
scripts.forEach((s) => vm.runInContext(fs.readFileSync(path.join(root, s), 'utf8'), ctx, { filename: s }));
const NC = ctx.NC;

function inputs(def, over) {
  const ex = typeof def.example === 'function' ? def.example() : def.example || {};
  const raw = {};
  def.inputs.forEach((i) => { raw[i.id] = i.value; });
  Object.assign(raw, ex, over || {});
  const v = {};
  def.inputs.forEach((i) => {
    const x = raw[i.id];
    v[i.id] = i.type === 'number' ? (x === '' || x === undefined || x === null ? NaN : Number(x)) : String(x === undefined ? '' : x);
  });
  return v;
}
const SIGN = ' — verified by ________ date ________';
const box = '- [ ] ';
const refName = (id) => (NC.refs[id] ? NC.refs[id].authors.split(/[;,]/)[0] + ' ' + NC.refs[id].year : id);
const asList = (r) => (Array.isArray(r) ? r : r ? [r] : []);
const md = (s) => String(s).replace(/\|/g, '\\|');

function collectSteps(def) {
  const runs = [{}];
  def.inputs.filter((i) => i.type === 'select').forEach((i) => i.options.forEach((o) => runs.push({ [i.id]: o[0] })));
  const seen = new Map();
  let ok = 0;
  runs.forEach((over) => {
    let out;
    try { out = def.compute(inputs(def, over)); ok++; } catch (e) { return; }
    out.steps.forEach((s) => {
      if (s.kind !== 'step' || !(s.formula || s.tex)) return;
      const key = s.tex || s.formula;
      if (!seen.has(key)) seen.set(key, { title: s.title, formula: s.formula, tex: s.tex || NC.toTex(s.formula), refs: asList(s.ref) });
      else asList(s.ref).forEach((r) => { if (!seen.get(key).refs.includes(r)) seen.get(key).refs.push(r); });
    });
  });
  return { steps: [...seen.values()], branches: ok };
}

const L = [];
const date = new Date().toISOString().slice(0, 10);
L.push('# NanoCalc expert review sheet', '');
L.push('_Generated by `node tools/review-sheet.js` on ' + date + ' from the code itself (' + NC.calculators.length + ' calculators, ' + Object.keys(NC.refs).length + ' references). Regenerate it after any change to a calculator._', '');
L.push('## How to review', '');
L.push('This sheet is for a scientist with expertise in nanomaterials characterization. For every item, please check it against the cited source and tick it, adding your initials and the date. Note problems inline or open an issue.', '');
L.push('1. **Formulas.** Each equation as the app displays it (plain text and LaTeX). Check it matches the cited source, including the definitions of symbols, units and any numerical prefactor.');
L.push('2. **Default parameters and presets.** Check that typical values (densities, wavelengths, shape factors, empirical coefficients) are correct and that their source is appropriate.');
L.push('3. **References.** Check that each citation exists, the bibliographic details and DOI are correct, and the source actually supports the use made of it.');
L.push('4. **Validity limits.** In the app, open the calculator and read its warnings and notes. Check that the stated range of validity matches the literature.');
L.push('', 'Run the app (`node tools/serve.js`, then http://localhost:8080) to see each formula in context with worked numbers, and `node tests/run-tests.js` for the automated checks against known values.', '');

L.push('## Physical constants (CODATA 2018)', '');
Object.keys(NC.C).forEach((k) => L.push(box + '`' + k + '` = ' + NC.C[k] + SIGN));
L.push(box + '`hc/e` = ' + NC.HC_EV_NM + ' eV·nm' + SIGN);
L.push(box + 'Ideal-gas molar volume at STP = ' + NC.VM_STP + ' cm³/mol' + SIGN, '');

L.push('## Material data', '', '| ✓ | Key | Material | ρ (g/cm³) | M (g/mol) | T_m (K) | ΔH_f (kJ/mol) | Verified by / date |', '|---|---|---|---|---|---|---|---|');
Object.keys(NC.materials).forEach((k) => {
  const m = NC.materials[k];
  L.push('| ☐ | ' + k + ' | ' + md(m.label) + ' | ' + m.rho + ' | ' + m.M + ' | ' + (m.Tm || '') + ' | ' + (m.dHf || '') + ' | |');
});
L.push('');

NC.categories.forEach((cat) => {
  const list = NC.calculators.filter((c) => c.category === cat.id);
  if (!list.length) return;
  L.push('## ' + cat.label, '');
  list.forEach((def) => {
    const { steps, branches } = collectSteps(def);
    L.push('### ' + def.title + ' (`' + def.id + '`)', '', def.description, '');
    L.push('**Formulas** (' + steps.length + ' distinct, from ' + branches + ' input branches)', '');
    steps.forEach((s) => {
      L.push(box + '**' + s.title + '**: `' + String(s.formula || '').replace(/`/g, "'") + '`' + (s.tex ? '  ' : ''));
      if (s.tex) L.push('  $' + s.tex + '$');
      L.push('  ' + (s.refs.length ? 'Cites: ' + s.refs.map(refName).join('; ') : 'No citation (definition or algebra)') + '.' + SIGN);
    });
    const nums = def.inputs.filter((i) => i.type === 'number' && typeof i.value === 'number' && !isNaN(i.value));
    if (nums.length) {
      L.push('', '**Default parameters**', '');
      nums.forEach((i) => L.push(box + md(i.label) + ' = ' + i.value + (i.unit ? ' ' + i.unit : '') + (i.help ? ' (' + i.help + ')' : '') + SIGN));
    }
    if (def.presets && def.presets.length) {
      L.push('', '**Presets**', '');
      def.presets.forEach((p) => L.push(box + md(p.label) + ': ' + Object.keys(p.values).map((k) => k + ' = ' + p.values[k]).join(', ') + SIGN));
      if (def.presetNote) L.push('', '_' + def.presetNote + '_');
    }
    const refs = [];
    asList(def.refs).concat(...steps.map((s) => s.refs)).forEach((r) => { if (NC.refs[r] && !refs.includes(r)) refs.push(r); });
    L.push('', '**References**', '');
    refs.forEach((r) => L.push(box + NC.formatRefText(NC.refs[r]) + SIGN));
    L.push('');
  });
});

const out = path.join(root, 'docs', 'REVIEW.md');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join('\n') + '\n');
const boxes = L.filter((l) => l.startsWith(box)).length + Object.keys(NC.materials).length;
console.log('Wrote ' + path.relative(root, out) + ': ' + NC.calculators.length + ' calculators, ' + boxes + ' items to sign off.');
